-- 6. DEPOSIT PROCEDURE
CREATE OR REPLACE PROCEDURE BE_DEPOSIT(
    P_ACCOUNT_ID NUMBER,
    P_AMOUNT NUMBER
)
AS
BEGIN
    IF P_AMOUNT <= 0 THEN
        DBMS_OUTPUT.PUT_LINE('Invalid deposit amount');
    ELSE
        UPDATE BE_ACCOUNTS
        SET BALANCE = BALANCE + P_AMOUNT
        WHERE ACCOUNT_ID = P_ACCOUNT_ID
        AND STATUS = 'ACTIVE';

        IF SQL%ROWCOUNT = 0 THEN
            DBMS_OUTPUT.PUT_LINE('Account not found or inactive');
        ELSE
            INSERT INTO BE_TRANSACTIONS
            VALUES (BE_TRANSACTIONS_SEQ.NEXTVAL, P_ACCOUNT_ID,
            'DEPOSIT', P_AMOUNT, SYSDATE, 'Money deposited');

            COMMIT;
            DBMS_OUTPUT.PUT_LINE('Deposit successful!');
        END IF;
    END IF;
END;
/

-- 7. WITHDRAW PROCEDURE
CREATE OR REPLACE PROCEDURE BE_WITHDRAW(
    P_ACCOUNT_ID NUMBER,
    P_AMOUNT NUMBER
)
AS
    V_BALANCE NUMBER;
BEGIN
    SELECT BALANCE INTO V_BALANCE
    FROM BE_ACCOUNTS
    WHERE ACCOUNT_ID = P_ACCOUNT_ID
    AND STATUS = 'ACTIVE'
    FOR UPDATE;

    IF P_AMOUNT <= 0 THEN
        DBMS_OUTPUT.PUT_LINE('Invalid withdrawal amount');
    ELSIF V_BALANCE < P_AMOUNT THEN
        DBMS_OUTPUT.PUT_LINE('Insufficient balance');
    ELSE
        UPDATE BE_ACCOUNTS
        SET BALANCE = BALANCE - P_AMOUNT
        WHERE ACCOUNT_ID = P_ACCOUNT_ID;

        INSERT INTO BE_TRANSACTIONS
        VALUES (BE_TRANSACTIONS_SEQ.NEXTVAL, P_ACCOUNT_ID,
        'WITHDRAWAL', P_AMOUNT, SYSDATE, 'Money withdrawn');

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Withdrawal successful!');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Account not found or inactive');
END;
/

-- 8. TRANSFER PROCEDURE
CREATE OR REPLACE PROCEDURE BE_TRANSFER(
    P_FROM NUMBER,
    P_TO NUMBER,
    P_AMOUNT NUMBER
)
AS
    V_BALANCE NUMBER;
    V_COUNT NUMBER;
BEGIN
    IF P_AMOUNT <= 0 OR P_FROM = P_TO THEN
        DBMS_OUTPUT.PUT_LINE('Invalid transfer details');
        RETURN;
    END IF;

    SELECT COUNT(*) INTO V_COUNT
    FROM BE_ACCOUNTS
    WHERE ACCOUNT_ID = P_TO AND STATUS = 'ACTIVE';

    IF V_COUNT = 0 THEN
        DBMS_OUTPUT.PUT_LINE('Receiver account not found or inactive');
        RETURN;
    END IF;

    SELECT BALANCE INTO V_BALANCE
    FROM BE_ACCOUNTS
    WHERE ACCOUNT_ID = P_FROM AND STATUS = 'ACTIVE'
    FOR UPDATE;

    IF V_BALANCE < P_AMOUNT THEN
        DBMS_OUTPUT.PUT_LINE('Insufficient balance');
    ELSE
        UPDATE BE_ACCOUNTS
        SET BALANCE = BALANCE - P_AMOUNT
        WHERE ACCOUNT_ID = P_FROM;

        UPDATE BE_ACCOUNTS
        SET BALANCE = BALANCE + P_AMOUNT
        WHERE ACCOUNT_ID = P_TO;

        INSERT INTO BE_TRANSACTIONS
        VALUES (BE_TRANSACTIONS_SEQ.NEXTVAL, P_FROM,
        'TRANSFER OUT', P_AMOUNT, SYSDATE, 'Money transferred');

        INSERT INTO BE_TRANSACTIONS
        VALUES (BE_TRANSACTIONS_SEQ.NEXTVAL, P_TO,
        'TRANSFER IN', P_AMOUNT, SYSDATE, 'Money received');

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Transfer successful!');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Sender account not found or inactive');
END;
/

-- 9. BALANCE CHECK PROCEDURE
CREATE OR REPLACE PROCEDURE BE_CHECK_BALANCE(
    P_ACCOUNT_ID NUMBER
)
AS
    V_BALANCE NUMBER;
BEGIN
    SELECT BALANCE INTO V_BALANCE
    FROM BE_ACCOUNTS
    WHERE ACCOUNT_ID = P_ACCOUNT_ID;

    DBMS_OUTPUT.PUT_LINE('Account Balance: Rs. ' || V_BALANCE);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Account not found');
END;
/

